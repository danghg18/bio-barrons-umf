import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const window={};
vm.runInNewContext(await readFile(new URL('../assets/js/analytics-sync.js',import.meta.url),'utf8').catch(()=>''),{window});
assert.equal(typeof window.BBAnalyticsSync?.merge,'function','History synchronization exposes a deterministic record merger');
const merge=window.BBAnalyticsSync.merge;
const run={version:1,id:'run',storageKey:'quiz',questionIds:['a','b'],startedAt:'2026-09-01T00:00:00Z',answers:{},status:'active'};
const a={...run,answers:{a:{verified:true,correct:false,selected:['B'],at:'2026-09-01T01:00:00Z',eventId:'e1'}}};
const b={...run,answers:{b:{verified:true,correct:true,selected:['A'],at:'2026-09-01T02:00:00Z',eventId:'e2'}}};
const key='bb.analytics.v1:run:run';
let joined=merge(key,a,b);
assert.equal(Object.keys(joined.answers).length,2,'Independent offline answers survive');
assert.equal(joined.status,'completed');
assert.equal(joined.completedAt,'2026-09-01T02:00:00Z','Completion uses actual latest answer date');
assert.deepEqual(JSON.parse(JSON.stringify(joined)),JSON.parse(JSON.stringify(merge(key,b,a))),'Merge commutes');
const conflict={...a,answers:{a:{...a.answers.a,eventId:'e3',at:'2026-09-01T03:00:00Z',correct:true}}};
joined=merge(key,a,conflict);
assert.equal(joined.answers.a.correct,false,'Original initial result remains unchanged');
assert.equal(joined.answerConflicts.a.length,2,'Concurrent same-question results remain inspectable');
assert.equal(merge(key,{...a,deleted:true},b).deleted,true,'Deletion beats an offline edit');
assert.equal(merge(key,a,{...b,closedAt:'2026-09-02T00:00:00Z',status:'stopped'}).closedAt,'2026-09-02T00:00:00Z');
const metaKey='bb.analytics.v1:metadata:quiz';
const old={version:1,key:'quiz',since:'2026-09-01',first:{a:'e1'},unknown:['b'],activeRunId:'old',syncUpdatedAt:'2026-09-02'};
const next={...old,first:{c:'e2'},unknown:['d'],activeRunId:'new',syncUpdatedAt:'2026-09-03'};
assert.deepEqual(JSON.parse(JSON.stringify(merge(metaKey,old,next).first)),{a:'e1',c:'e2'});
assert.equal(merge(metaKey,old,next).activeRunId,'new');
assert.equal(merge(metaKey,old,{...next,clearedAt:'2026-09-03',first:{}}).first.a,undefined,'Clear resets first-event bookkeeping');
console.log('Analytics deterministic history merges passed.');
