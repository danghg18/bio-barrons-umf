import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const disk=new Map(), window=Object.assign(new EventTarget(), {localStorage:{getItem:k=>disk.get(k)??null,setItem:(k,v)=>disk.set(k,v),removeItem:k=>disk.delete(k),key:i=>[...disk.keys()][i],get length(){return disk.size;}}});
const context={window,document:new EventTarget(),CustomEvent};
for(const file of ['personal-records','user-storage']) vm.runInNewContext(await readFile(new URL('../assets/js/'+file+'.js',import.meta.url),'utf8'),context);
const s=window.BBUserStorage, key='bb.highlight.v1:first';
s.set(key,{version:1,id:'first',color:'yellow'});
s.set('bb.highlight-clear.v1:guest-clear',{version:1,id:'guest-clear',chapterNum:2});
s.set('bb.highlight.v1:old-guest',{version:1,id:'old-guest',chapterNum:2,clearIds:[]});
s.activate('alice');
assert.equal(s.get('bb.highlight-clear.v1:guest-clear'),null,'Guest clearing cannot clear unrelated account annotations');
assert.equal(s.get('bb.highlight.v1:old-guest'),null,'Cleared guest records are not resurrected by import');
assert.equal(s.get(key)?.color,'yellow','Guest highlights imported at login');
assert.ok(s.snapshot().pending[key],'Imported highlight queued durably');
s.hydrate({[key]:{version:1,id:'first',deleted:true}});
assert.equal(s.get(key).deleted,true,'Remote tombstone beats pending offline edit');
s.set(key,{version:1,id:'first',color:'pink'});
assert.equal(s.get(key).deleted,true,'Deleted IDs cannot be resurrected by stale local writers');
s.activate('bob');assert.equal(s.get(key),null);
assert.equal(s.canClaimGuestRecords(),false,'Guest history belongs to first account');
s.activate('alice');assert.equal(s.canClaimGuestRecords(),true);
s.claimGuestRecords({'bb.analytics.v1:attempt:one':{version:1,id:'one',at:'original-date'}});
assert.equal(s.get('bb.analytics.v1:attempt:one').at,'original-date');
assert.equal(s.entries('bb.analytics.v1:').length,1);
s.claimGuestRecords({'bb.analytics.v1:attempt:one':{version:1,id:'one',at:'original-date'}});
assert.equal(s.entries('bb.analytics.v1:').length,1);
s.claimGuestRecords({'bb.analytics.v1:attempt:one':{version:1,id:'one',at:'different-date'}});
assert.equal(s.get('bb.analytics.v1:attempt:one').at,'original-date','Repeated guest imports cannot replace immutable account attempts');
